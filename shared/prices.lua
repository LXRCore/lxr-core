local P = LXRShared.Prices
for name, price in pairs(P.items) do
    local it = LXRShared.Items and LXRShared.Items[name]
    if it then it.value = price end
end
for breed, price in pairs(P.horses) do
    local b = LXRShared.HorseBreeds and LXRShared.HorseBreeds[breed]
    if b then b.price = price end
end
for model, h in pairs(LXRShared.Horses or {}) do
    local b = LXRShared.HorseBreeds[h.breed]
    if b and P.horses[h.breed] then h.price = math.floor(b.price * (h.priceMult or 1.0) + 0.5) end
end
for model, price in pairs(P.vehicles) do
    local v = LXRShared.Vehicles and LXRShared.Vehicles[model]
    if v then v.price = price end
end

---Every catalog item without a ledger entry (validation / audits).
function LXRShared.UnpricedItems()
    local out = {}
    for name in pairs(LXRShared.Items or {}) do if P.items[name] == nil then out[#out + 1] = name end end
    table.sort(out)
    return out
end
